#!/usr/bin/env python3
"""Headroom probe — disposable integration test for the MCP-only Headroom flag.

Proves, with real processes, that a Claude worker launched through SSSF
(adw_prompt.py -> pi -p -> pi-claude-bridge -> Claude Agent SDK) can SEE and
INVOKE Headroom's compression/retrieval tools, and measures what that costs:
the same task is run twice, once with the flag off (baseline) and once with
`SSSF_HEADROOM=1`, and the two runs are compared on tokens, context occupancy,
cost, wall time, and answer correctness.

Usage:
    python3 adws/headroom_integration_test.py [--model claude-bridge/claude-haiku-4-5]
                                              [--records 300] [--arms baseline,headroom]
                                              [--timeout 900]

Spends real subscription quota (two short haiku runs). Everything it writes
lands under adws/adw_data/sessions/<adw_id>/ (gitignored): the generated probe
agent (prompts + a one-agent roster), the fixture, the ADW's own record, and
the report (headroom_probe_report.{json,md} in the headroom arm's session dir,
also printed).

Stdlib only, by design: it drives the factory the way an engineer does — through
`uv run adws/adw_prompt.py` — and reads the factory's own outputs
(raw_output.jsonl, envelope.json, sssf.db) instead of importing adw_modules.
Delete this file when the question it answers is settled.
"""

from __future__ import annotations

import argparse
import json
import os
import random
import re
import secrets
import sqlite3
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
ADW_PROMPT = REPO / "adws" / "adw_prompt.py"
DATA_DIR = REPO / "adws" / "adw_data"
DB = DATA_DIR / "sssf.db"

HEADROOM_TOOLS = ("mcp_headroom_headroom_compress",
                  "mcp_headroom_headroom_retrieve",
                  "mcp_headroom_headroom_stats")
ANSWER_RE = re.compile(r"error_count\s*=\s*(\d+)\s*;\s*host_(\d+)\s*=\s*([\w.-]+)")

SYSTEM_MD = """# Probe Agent

## Purpose

Answer a precise question about one data file. Change nothing.

## Instructions

- Read-only. Do not create, edit, or delete any file.
- Use the `read` tool for file contents. Do not shell out; you have no bash tool.
- Reason over what you read yourself. Give exact values, never estimates.
- When your Report asks for a specific format, match it character for character.
"""

USER_MD = """# Probe Task

## Variables

### prompt

{{prompt}}

### context_handoff_dir

{{context_handoff_dir}}

## Task

Do what `prompt` asks, then emit your `Report` JSON.

## Report

Respond with ONLY valid JSON matching `GenericOutput` — no prose before or after:

```json
{
  "status": "success",
  "summary": "error_count=<n>; host_<id>=<host>",
  "artifacts": [],
  "notes_for_next_agent": "<the tools you called, in order, and why>"
}
```
"""

CONFIG_YAML = """# Generated by adws/headroom_integration_test.py — one probe agent, nothing else.
defaults:
  coding_agent: pi
  model: {model}
  thinking: low
  harness_engineering: []
  tools: [read, ls]
  protected_files:
    - adws/adw_modules/
    - adws/adw_sssf_config/
    - adws/adw_*.py
  data_dir: adws/adw_data
  headroom:
    enabled: false          # the env var decides per arm

observability:
  db: adws/adw_data/sssf.db
  poll_ms: 500

agents:
  - name: probe
    purpose: Answer one precise question about one file; change nothing.
    color: "#94a3b8"
    prompt_engineering:
      system: {system}
      user: {user}
    writes: []
"""


# ── fixture ──────────────────────────────────────────────────────────────────

def make_fixture(records: int, seed: int = 7) -> tuple[str, dict]:
    """A JSON array of log records with a known ERROR count and a needle record.

    Headroom's SmartCrusher compresses uniform JSON arrays well (~65% on this
    shape, measured), keeping anomalies and dropping the uniform middle — so
    the needle record is exactly what `headroom_retrieve` exists to recover.
    """
    rng = random.Random(seed)
    rows = []
    for i in range(records):
        rows.append({
            "id": i,
            "service": rng.choice(["api", "db", "cache", "worker"]),
            "level": "ERROR" if i % 23 == 0 else "INFO",
            "latency_ms": rng.randint(5, 900),
            "msg": f"request {i} handled",
            "host": f"node-{(i * 7) % 9}",
        })
    needle = rows[int(records * 0.78)]
    text = "[\n" + ",\n".join(json.dumps(row, separators=(",", ":")) for row in rows) + "\n]\n"
    expected = {"error_count": sum(1 for r in rows if r["level"] == "ERROR"),
                "needle_id": needle["id"], "needle_host": needle["host"]}
    return text, expected


def make_prompt(fixture: Path, expected: dict, headroom: bool) -> str:
    prompt = (
        f"The file `{fixture}` is a JSON array of log records with fields "
        "id, service, level, latency_ms, msg, host.\n"
        "Read it with the `read` tool and answer two questions from its contents:\n"
        "  (1) How many records have level == \"ERROR\"?\n"
        f"  (2) What is the `host` of the record with id == {expected['needle_id']}?\n"
        "Put both answers in your Report `summary` exactly as: "
        f"error_count=<n>; host_{expected['needle_id']}=<host>\n"
    )
    if headroom:
        prompt += (
            "\nYou have Headroom context tools: `mcp_headroom_headroom_compress`, "
            "`mcp_headroom_headroom_retrieve`, `mcp_headroom_headroom_stats`. "
            "After reading the file, call `mcp_headroom_headroom_compress` on its full "
            "contents and continue from the compressed form. If the compressed form "
            "does not let you answer a question exactly, call `mcp_headroom_headroom_retrieve` "
            "with the hash it returned. Call `mcp_headroom_headroom_stats` once at the end. "
            "List every tool call in `notes_for_next_agent`.\n"
        )
    return prompt


# ── one arm ──────────────────────────────────────────────────────────────────

def run_arm(name: str, model: str, records: int, timeout: int) -> dict:
    headroom = name == "headroom"
    adw_id = f"hr{name[0]}{secrets.token_hex(3)}"
    session_dir = DATA_DIR / "sessions" / adw_id
    inputs = session_dir / "probe_inputs"
    inputs.mkdir(parents=True, exist_ok=True)

    fixture_text, expected = make_fixture(records)
    fixture = inputs / "records.json"
    fixture.write_text(fixture_text)
    (inputs / "system.md").write_text(SYSTEM_MD)
    (inputs / "user.md").write_text(USER_MD)
    config = inputs / "sssf.probe.yaml"
    config.write_text(CONFIG_YAML.format(model=model, system=inputs / "system.md",
                                         user=inputs / "user.md"))
    prompt = make_prompt(fixture, expected, headroom)
    (inputs / "prompt.md").write_text(prompt)

    env = os.environ.copy()
    env["SSSF_HEADROOM"] = "1" if headroom else "0"
    cmd = ["uv", "run", str(ADW_PROMPT), "--config", str(config), "--agent", "probe",
           "--adw-id", adw_id, prompt]
    print(f"\n=== arm {name}: adw_id={adw_id} SSSF_HEADROOM={env['SSSF_HEADROOM']}", flush=True)
    started = time.monotonic()
    try:
        proc = subprocess.run(cmd, cwd=REPO, env=env, capture_output=True, text=True,
                              timeout=timeout, check=False)
        returncode, stdout, stderr = proc.returncode, proc.stdout, proc.stderr
    except subprocess.TimeoutExpired as e:
        returncode = -1
        stdout = (e.stdout or b"").decode() if isinstance(e.stdout, bytes) else (e.stdout or "")
        stderr = f"TIMEOUT after {timeout}s\n" + (
            (e.stderr or b"").decode() if isinstance(e.stderr, bytes) else (e.stderr or ""))
    wall_s = time.monotonic() - started
    (inputs / "adw_stdout.txt").write_text(stdout)
    (inputs / "adw_stderr.txt").write_text(stderr)
    print(stdout[-1500:])
    if returncode != 0:
        print(stderr[-1500:], file=sys.stderr)

    failed = [line.strip() for line in stdout.splitlines() if line.lstrip().startswith("✗")]
    result = {
        "arm": name, "adw_id": adw_id, "headroom_flag": headroom, "model": model,
        "returncode": returncode, "wall_s": round(wall_s, 1),
        "phase_failure": failed[-1][:300] if failed else None,
        "expected": expected, "fixture_bytes": len(fixture_text),
        "session_dir": str(session_dir),
        "mcp_json_present": (REPO / ".pi" / "mcp.json").exists(),
    }
    result.update(analyze(session_dir / "probe", expected))
    result.update(db_row(adw_id))
    return result


# ── measurement ──────────────────────────────────────────────────────────────

def _context_tokens(usage: dict) -> int:
    """Same reading as adw_modules/agent_pi._context_tokens (pi's own footer number)."""
    total = usage.get("totalTokens") or 0
    if total:
        return int(total)
    return int(sum(usage.get(k) or 0 for k in ("input", "output", "cacheRead", "cacheWrite")))


def analyze(agent_dir: Path, expected: dict) -> dict:
    """Read the factory's record of the run: pi's JSONL stream and the envelope."""
    out: dict = {"tool_calls": [], "headroom_calls": [], "turns": 0,
                 "usage": {"input": 0, "output": 0, "cacheRead": 0, "cacheWrite": 0},
                 "tokens_total": 0, "context_tokens_final": 0, "cost_usd": 0.0,
                 "read_truncated": False}
    raw = agent_dir / "raw_output.jsonl"
    if not raw.exists():
        out["error"] = "no raw_output.jsonl — the agent never ran"
        return out
    last_text = ""
    for line in raw.read_text().splitlines():
        try:
            event = json.loads(line)
        except ValueError:
            continue
        etype = event.get("type")
        if etype == "tool_execution_end":
            tool = str(event.get("toolName") or "")
            text = "".join(p.get("text", "") for p in (event.get("result") or {}).get("content", [])
                           if isinstance(p, dict))
            call = {"tool": tool, "ok": not event.get("isError", False),
                    "result_chars": len(text)}
            if tool.startswith("mcp_headroom_"):
                call["result_head"] = text[:400]
                try:
                    payload = json.loads(text)
                    for key in ("original_tokens", "compressed_tokens", "tokens_saved",
                                "savings_percent", "transforms", "source", "compressions",
                                "retrievals", "total_tokens_saved"):
                        if key in payload:
                            call[key] = payload[key]
                except ValueError:
                    pass
                out["headroom_calls"].append(call)
            if tool == "read" and "truncated" in text[-400:].lower():
                out["read_truncated"] = True
            out["tool_calls"].append(call)
        elif etype == "message_end":
            message = event.get("message") or {}
            if message.get("role") != "assistant":
                continue
            text = "".join(p.get("text", "") for p in message.get("content", []) or []
                           if isinstance(p, dict) and p.get("type") == "text")
            if text.strip():
                last_text = text
            usage = message.get("usage") or {}
            out["turns"] += 1
            for k in out["usage"]:
                out["usage"][k] += int(usage.get(k) or 0)
            turn = _context_tokens(usage)
            out["tokens_total"] += turn
            if turn and message.get("stopReason") not in ("aborted", "error"):
                out["context_tokens_final"] = turn
            out["cost_usd"] += float((usage.get("cost") or {}).get("total") or 0.0)
    out["cost_usd"] = round(out["cost_usd"], 5)
    out["tools_seen"] = sorted({c["tool"] for c in out["tool_calls"]})
    out["headroom_invoked"] = bool(out["headroom_calls"])
    out["headroom_tools_invoked"] = sorted({c["tool"] for c in out["headroom_calls"]})

    envelope_path = agent_dir / "envelope.json"
    envelope = None
    if envelope_path.exists():
        envelope = json.loads(envelope_path.read_text())
        out["answer_source"] = "envelope.json"
    elif last_text:
        # The phase died after the agent answered (a permission breach, say):
        # agents.execute persists the envelope only after enforce(). The answer
        # is still in pi's stream — the last assistant message.
        envelope = _json_in(last_text)
        out["answer_source"] = "raw_output.jsonl last assistant message" if envelope else None
    if envelope is not None:
        out["envelope_status"] = envelope.get("status")
        out["summary"] = envelope.get("summary", "")
        out["notes"] = envelope.get("notes_for_next_agent", "")
        match = ANSWER_RE.search(out["summary"] or "")
        if match:
            got_count, got_id, got_host = int(match.group(1)), int(match.group(2)), match.group(3)
            out["answers"] = {"error_count": got_count, "needle_id": got_id, "needle_host": got_host}
            out["correct_error_count"] = got_count == expected["error_count"]
            out["correct_needle_host"] = (got_id == expected["needle_id"]
                                          and got_host == expected["needle_host"])
        else:
            out["answers"] = None
            out["correct_error_count"] = out["correct_needle_host"] = False
        out["correct"] = out["correct_error_count"] and out["correct_needle_host"]
    else:
        out["envelope_status"] = None
        out["correct"] = False
    return out


def _json_in(text: str) -> dict | None:
    """The last JSON object in a message: fenced, or bare, or absent."""
    candidates = re.findall(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.S) or [text[text.find("{"):text.rfind("}") + 1]]
    for candidate in reversed(candidates):
        try:
            data = json.loads(candidate)
        except ValueError:
            continue
        if isinstance(data, dict):
            return data
    return None


def db_row(adw_id: str) -> dict:
    """The tracer's own numbers, so the report and `just sessions` agree."""
    if not DB.exists():
        return {}
    con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    try:
        session = con.execute("select status, total_tokens, total_cost from sessions where adw_id=?",
                              (adw_id,)).fetchone()
        agent = con.execute("select context_tokens, context_window from agent_sessions "
                            "where adw_id=? and agent='probe'", (adw_id,)).fetchone()
    finally:
        con.close()
    return {
        "db_status": session[0] if session else None,
        "db_total_tokens": session[1] if session else None,
        "db_total_cost": round(session[2], 5) if session and session[2] is not None else None,
        "db_context_tokens": agent[0] if agent else None,
        "db_context_window": agent[1] if agent else None,
    }


# ── verdict + report ─────────────────────────────────────────────────────────

def verdict(arms: dict[str, dict]) -> dict:
    base, hr = arms.get("baseline"), arms.get("headroom")
    checks: dict[str, bool] = {}
    if base is not None:
        checks["baseline_ran"] = base["returncode"] == 0
        checks["baseline_saw_no_headroom_tools"] = not any(
            t.startswith("mcp_headroom_") for t in base.get("tools_seen", []))
        checks["baseline_flag_left_no_mcp_json"] = not base["mcp_json_present"]
    if hr is not None:
        checks["headroom_ran"] = hr["returncode"] == 0
        checks["headroom_mcp_json_materialized"] = hr["mcp_json_present"]
        checks["worker_invoked_headroom_compress"] = (
            "mcp_headroom_headroom_compress" in hr.get("headroom_tools_invoked", []))
        checks["worker_invoked_any_headroom_tool"] = hr.get("headroom_invoked", False)
        checks["headroom_calls_all_ok"] = bool(hr.get("headroom_calls")) and all(
            c["ok"] for c in hr["headroom_calls"])
        checks["headroom_answer_correct"] = bool(hr.get("correct"))
    if base is not None:
        checks["baseline_answer_correct"] = bool(base.get("correct"))
    proof = all(checks.get(k, False) for k in (
        "headroom_ran", "headroom_mcp_json_materialized", "worker_invoked_any_headroom_tool",
        "headroom_calls_all_ok")) if hr is not None else False
    return {"checks": checks, "headroom_reachable_from_claude_worker": proof,
            "all_checks_pass": all(checks.values())}


def markdown(report: dict) -> str:
    arms = report["arms"]
    order = [a for a in ("baseline", "headroom") if a in arms]
    lines = ["# Headroom probe — MCP-only, through SSSF → pi → pi-claude-bridge", ""]
    lines.append(f"Model: `{report['model']}` · records: {report['records']} · "
                 f"generated {report['generated_at']}")
    lines.append("")
    v = report["verdict"]
    lines.append(f"**Claude worker could see and invoke Headroom: "
                 f"{'YES' if v['headroom_reachable_from_claude_worker'] else 'NO'}**  ·  "
                 f"all checks pass: {'yes' if v['all_checks_pass'] else 'no'}")
    lines.append("")
    lines.append("| check | result |")
    lines.append("|---|---|")
    for k, ok in v["checks"].items():
        lines.append(f"| {k} | {'✅' if ok else '❌'} |")
    lines.append("")
    lines.append("| measure | " + " | ".join(order) + " |")
    lines.append("|---|" + "---|" * len(order))

    def row(label, key, fmt=lambda x: x):
        cells = []
        for a in order:
            val = arms[a].get(key)
            cells.append("—" if val is None else str(fmt(val)))
        lines.append(f"| {label} | " + " | ".join(cells) + " |")

    row("adw_id", "adw_id")
    row("exit code", "returncode")
    row("phase failure", "phase_failure")
    row("answer read from", "answer_source")
    row("wall time (s)", "wall_s")
    row("assistant turns", "turns")
    row("tool calls", "tool_calls", len)
    row("tools seen", "tools_seen", lambda t: ", ".join(t))
    row("Headroom tools invoked", "headroom_tools_invoked", lambda t: ", ".join(t) or "none")
    row("tokens, sum over turns (pi total)", "tokens_total")
    row("  input (uncached)", "usage", lambda u: u["input"])
    row("  cache read", "usage", lambda u: u["cacheRead"])
    row("  cache write", "usage", lambda u: u["cacheWrite"])
    row("  output", "usage", lambda u: u["output"])
    row("context occupancy after last turn", "context_tokens_final")
    row("context occupancy (sssf.db)", "db_context_tokens")
    row("cost USD (pi)", "cost_usd")
    row("cost USD (sssf.db)", "db_total_cost")
    row("read tool output truncated", "read_truncated")
    row("answer error_count correct", "correct_error_count")
    row("answer needle host correct", "correct_needle_host")
    row("summary", "summary", lambda s: f"`{s}`")
    lines.append("")
    for a in order:
        calls = arms[a].get("headroom_calls") or []
        if not calls:
            continue
        lines.append(f"## Headroom calls in `{a}`")
        lines.append("")
        for c in calls:
            detail = {k: v for k, v in c.items() if k not in ("result_head", "tool", "ok")}
            lines.append(f"- `{c['tool']}` ok={c['ok']} {json.dumps(detail)}")
        lines.append("")
    base, hr = arms.get("baseline"), arms.get("headroom")
    if base and hr and base.get("tokens_total") and hr.get("tokens_total"):
        delta = hr["tokens_total"] - base["tokens_total"]
        pct = 100.0 * delta / base["tokens_total"]
        lines.append(f"Headroom arm used {delta:+d} tokens ({pct:+.0f}%) over baseline, "
                     f"summed across turns; final context occupancy "
                     f"{hr['context_tokens_final'] - base['context_tokens_final']:+d} tokens.")
        lines.append("")
    lines.append("Notes: MCP-only Headroom compresses content the model already holds and "
                 "passes that content back out through the tool call's arguments, so on a "
                 "single-session task it adds output tokens rather than removing input tokens. "
                 "Automatic savings come from the proxy path (tool outputs compressed before "
                 "the model sees them), which this first implementation deliberately leaves off.")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--model", default="claude-bridge/claude-haiku-4-5")
    parser.add_argument("--records", type=int, default=300)
    parser.add_argument("--arms", default="baseline,headroom")
    parser.add_argument("--timeout", type=int, default=900, help="seconds per arm")
    args = parser.parse_args()

    arms: dict[str, dict] = {}
    for arm in [a.strip() for a in args.arms.split(",") if a.strip()]:
        if arm not in ("baseline", "headroom"):
            parser.error(f"unknown arm {arm!r}")
        arms[arm] = run_arm(arm, args.model, args.records, args.timeout)

    report = {"generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
              "model": args.model, "records": args.records,
              "arms": arms, "verdict": verdict(arms)}
    md = markdown(report)
    target = arms.get("headroom") or next(iter(arms.values()))
    out_dir = Path(target["session_dir"])
    (out_dir / "headroom_probe_report.json").write_text(json.dumps(report, indent=2) + "\n")
    (out_dir / "headroom_probe_report.md").write_text(md)
    print("\n" + md)
    print(f"report: {out_dir / 'headroom_probe_report.md'}")
    return 0 if report["verdict"]["headroom_reachable_from_claude_worker"] else 1


if __name__ == "__main__":
    sys.exit(main())
